# UYGULAMA 30: Şehirlerden oluşan tuple oluşturma

# Şehir isimlerini tuple içinde saklayalım
sehirler = ("Bursa", "İstanbul", "Ankara", "İzmir")

# Tuple'ın tamamını yazdıralım
print("Şehirler:", sehirler)

# İlk şehri yazdıralım
print("İlk şehir:", sehirler[0])

# Son şehri yazdıralım
print("Son şehir:", sehirler[-1])

# Şehir sayısını bulalım
print("Şehir sayısı:", len(sehirler))
# UYGULAMA 38: Öğrenci bilgilerini sözlükte saklama

# Öğrenci sözlüğü oluşturalım
ogrenci = {
    "ad": "Ayşe",
    "soyad": "Yılmaz",
    "yas": 20,
    "not": 85
}

# Sözlüğün tamamını yazdıralım

# UYGULAMA : Küme üzerinde işlemler yapma

# Meyve kümesi oluşturalım
meyveler = {"Elma", "Armut", "Muz"}

# Yeni eleman ekleyelim
meyveler.add("Çilek")

print("Eleman eklendi:", meyveler)

# Armut elemanını çıkaralım
meyveler.remove("Armut")

print("Eleman çıkarıldı:", meyveler)

# Meyve sayısını bulalım
print("Meyve sayısı:", len(meyveler))
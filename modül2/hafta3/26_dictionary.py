# UYGULAMA 39: Sözlüğe yeni bilgi ekleme ve güncelleme

# Öğrenci sözlüğünü oluşturalım
ogrenci = {
    "ad": "Mehmet",
    "yas": 19,
    "not": 70
}

# Öğrencinin notunu güncelleyelim
ogrenci["not"] = 90

# Sözlüğe yeni bir bilgi ekleyelim
ogrenci["bolum"] = "Bilgisayar"

# Güncel bilgileri gösterelim
print("Güncel öğrenci bilgileri:", ogrenci)
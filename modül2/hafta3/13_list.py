# UYGULAMA : Öğrenci isimlerinden liste oluşturma

# Öğrencilerin isimlerini listeye ekleyelim
ogrenciler = ["Ayşe", "Mehmet", "Elif", "Ahmet"]

# Listenin tamamını yazdıralım
print("Öğrenciler:", ogrenciler)

# İlk öğrenciyi yazdıralım
print("İlk öğrenci:", ogrenciler[0])

# İkinci öğrenciyi yazdıralım
print("İkinci öğrenci:", ogrenciler[1])

# Son öğrenciyi yazdıralım
print("Son öğrenci:", ogrenciler[-1])

# Öğrenci sayısını bulalım
print("Öğrenci sayısı:", len(ogrenciler))
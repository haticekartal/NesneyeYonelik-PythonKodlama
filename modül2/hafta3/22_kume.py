# UYGULAMA 35: Tekrarlanan sayıları küme ile kaldırma

# Tekrar eden sayılar içeren liste
sayilar = [1, 2, 2, 3, 4, 4, 5, 5]

# Listeyi kümeye dönüştürelim
benzersiz_sayilar = set(sayilar)

